// ClipboardMonitor.swift – „Skopiowano” i (opcjonalnie) krótka historia schowka
//
// Prywatność: w tle sprawdzamy tylko, ŻE coś skopiowano i jakiego rodzaju (tekst, obraz, pliki) –
// bez czytania treści. Treść tekstu odczytujemy wyłącznie, gdy w Ustawieniach włączono
// „Historię schowka”. Historia jest tylko w pamięci, nic nie trafia na dysk.

import Cocoa

final class ClipboardMonitor {

    static let shared = ClipboardMonitor()

    enum Copied {
        case text(String?)   // treść tylko przy włączonej historii
        case image
        case files(Int)
    }

    var onCopy: ((Copied) -> Void)?

    private var lastCount = NSPasteboard.general.changeCount
    private var ownCount: Int?
    private var lastText: String?
    private var timer: Timer?
    private var pending: DispatchWorkItem?
    private var lastChangeAt = Date.distantPast

    /// Porównanie licznika schowka – co 0,5 s (w trybie niskiego zużycia energii co 1,5 s).
    func start() {
        stop()
        lastCount = NSPasteboard.general.changeCount
        let interval = Prefs.lowPower ? 1.5 : 0.5
        let t = Timer.scheduledTimer(withTimeInterval: interval, repeats: true) { [weak self] _ in self?.check() }
        t.tolerance = interval * 0.4
        timer = t
    }

    func stop() {
        timer?.invalidate()
        timer = nil
        pending?.cancel()
    }

    /// Wkłada tekst z historii z powrotem do schowka (bez ponownego „Skopiowano”).
    func copy(_ text: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(text, forType: .string)
        ownCount = pb.changeCount
        lastCount = pb.changeCount
        lastText = text
    }

    private func check() {
        let count = NSPasteboard.general.changeCount
        guard count != lastCount else { return }
        lastCount = count
        guard count != ownCount else { return }
        // Niektóre programy (np. iWorkBar przy zmianie koloru) używają schowka tylko na moment
        // i zaraz go przywracają – dwie zmiany w krótkim odstępie traktujemy jako taką chwilową
        // operację i nic nie pokazujemy.
        let burst = Date().timeIntervalSince(lastChangeAt) < 1.5
        lastChangeAt = Date()
        pending?.cancel()
        if burst { return }
        let work = DispatchWorkItem { [weak self] in self?.settle(count) }
        pending = work
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.7, execute: work)
    }

    private func settle(_ count: Int) {
        let pb = NSPasteboard.general
        guard pb.changeCount == count else { return }
        // Same rodzaje danych – to nie jest odczyt treści schowka.
        let types = pb.types ?? []
        let raw = Set(types.map { $0.rawValue })
        // Hasła i dane tymczasowe (tak oznaczają je menedżery haseł) – pomijamy całkowicie.
        let skip = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                    "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        if skip.contains(where: { raw.contains($0) }) { return }

        if types.contains(.fileURL) {
            let count = pb.pasteboardItems?.count ?? 1
            onCopy?(.files(max(1, count)))
        } else if types.contains(.string) {
            guard Prefs.on(Prefs.clipboardHistory) else {
                onCopy?(.text(nil))
                return
            }
            guard let text = pb.string(forType: .string),
                  !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
            // Ten sam tekst co poprzednio (np. schowek przywrócony przez inny program) – bez powiadomienia.
            guard text != lastText else { return }
            lastText = text
            onCopy?(.text(text))
        } else if types.contains(.tiff) || types.contains(.png) {
            onCopy?(.image)
        }
    }
}
